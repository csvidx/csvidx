#!/usr/bin/env python3
"""The pandas scenario: "give me the rows of user X as a DataFrame".

Compared on the same file (generated by csvgen; columns order_id,user_id,ts,amount,status,comment):
  * csvidx.Index.get            (index lookup, then pandas.read_csv on just the matching rows)
  * pandas read_csv(chunksize)  (full scan, filter every chunk, concat)
  * DuckDB read_csv + WHERE     (full scan, .df()), if installed
Every result is checked to be the same DataFrame. Page cache of the CSV is evicted before each
full scan ("cold"); the csvidx numbers are given for a warm and a cold cache.

    python bench_pandas.py --csv ../data100/orders.csv --keys ../data100/keys.txt
"""
import argparse
import json
import os
import time

import pandas as pd

import csvidx

DTYPES = {"order_id": "int64", "user_id": "int64", "ts": "int64", "amount": "float64", "status": "object", "comment": "object"}


def evict(*paths):
    for p in paths:
        fd = os.open(p, os.O_RDONLY)
        try:
            os.posix_fadvise(fd, 0, 0, os.POSIX_FADV_DONTNEED)
        finally:
            os.close(fd)


def timeit(fn, repeat=1):
    best = None
    out = None
    for _ in range(repeat):
        t = time.perf_counter()
        out = fn()
        dt = time.perf_counter() - t
        best = dt if best is None else min(best, dt)
    return best, out


def pandas_scan(csv, keys, chunk=2_000_000):
    ks = set(keys)
    parts = []
    for c in pd.read_csv(csv, chunksize=chunk, dtype=DTYPES, keep_default_na=False):
        m = c[c["user_id"].isin(ks)]
        if len(m):
            parts.append(m)
    return pd.concat(parts, ignore_index=True) if parts else pd.DataFrame({k: pd.Series(dtype=v) for k, v in DTYPES.items()})


def duck_scan(csv, keys):
    import duckdb

    con = duckdb.connect()
    con.execute("set enable_progress_bar=false")
    lst = ",".join(str(k) for k in keys)
    return con.execute(f"select * from read_csv(?, header=true, nullstr='\x01') where user_id in ({lst}) order by order_id", [csv]).df()


def canon(df):
    return df.sort_values("order_id").reset_index(drop=True)[list(DTYPES)].astype({"comment": object, "status": object})


def same(a, b, what):
    a, b = canon(a), canon(b)
    pd.testing.assert_frame_equal(a, b, check_dtype=False, check_exact=False, rtol=1e-12)
    return len(a)


def fmt(s):
    return f"{s * 1000:.1f} ms" if s < 1 else f"{s:.2f} s"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", required=True)
    ap.add_argument("--keys", required=True)
    ap.add_argument("--batch", type=int, default=1000, help="size of the batch lookup")
    ap.add_argument("--no-duckdb", action="store_true")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    csv = os.path.abspath(a.csv)
    idxf = csv + ".idx"
    keys = [int(l) for l in open(a.keys) if l.strip()]
    gib = os.path.getsize(csv) / 2**30
    print(f"{csv}: {gib:.2f} GiB, csvidx {csvidx.__version__}, pandas {pd.__version__}\n")
    res = {"csv_gib": gib}

    # a typical key (a handful of rows) and a heavy one
    probe = csvidx.Index(csv)
    cnt = dict(zip(keys[:400], probe.count(keys[:400])))
    typical = next(k for k, c in cnt.items() if 5 <= c <= 30)
    heavy = max(cnt, key=cnt.get)
    batch = [k for k in keys if cnt.get(k, 1) > 0][: a.batch] if len(keys) >= a.batch else keys
    batch = list(dict.fromkeys(keys))[: a.batch]
    dt, _ = timeit(lambda: csvidx.Index(csv))
    res["open_ms"] = dt * 1e3
    print(f"csvidx.Index(...) opens in {fmt(dt)} (memory-mapped, nothing is loaded)\n")

    scenarios = [("one typical key", [typical]), ("one heavy key", [heavy]), (f"batch of {len(batch)} keys", batch)]
    print(f"{'scenario':<22}{'rows':>9}  {'csvidx warm':>12} {'csvidx cold':>12}  {'pandas chunks':>14} {'duckdb':>10}")
    res["scenarios"] = {}
    for name, ks in scenarios:
        idx = csvidx.Index(csv)
        evict(csv, idxf)
        t_cold, df_i = timeit(lambda: idx.get(ks, dtype=DTYPES, keep_default_na=False))
        t_warm, df_i = timeit(lambda: idx.get(ks, dtype=DTYPES, keep_default_na=False), repeat=3)

        evict(csv)
        t_pd, df_p = timeit(lambda: pandas_scan(csv, ks))
        n = same(df_i, df_p, "pandas")

        t_dk = None
        if not a.no_duckdb:
            try:
                evict(csv)
                t_dk, df_d = timeit(lambda: duck_scan(csv, ks))
                same(df_i, df_d, "duckdb")
            except ImportError:
                pass
        res["scenarios"][name] = dict(rows=n, csvidx_warm_s=t_warm, csvidx_cold_s=t_cold, pandas_s=t_pd, duckdb_s=t_dk)
        print(f"{name:<22}{n:>9}  {fmt(t_warm):>12} {fmt(t_cold):>12}  {fmt(t_pd):>14} {fmt(t_dk) if t_dk else '-':>10}   (results identical)")
    print("\nAll results are the same DataFrame (checked after sorting by order_id).")
    if a.out:
        with open(a.out, "w") as f:
            json.dump(res, f, indent=2)
        print(f"written to {a.out}")


if __name__ == "__main__":
    main()
